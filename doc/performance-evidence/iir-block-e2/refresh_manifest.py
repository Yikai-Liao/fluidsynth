#!/usr/bin/env python3
"""Refresh hashes in the E2 evidence manifest without rerunning experiments."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
MANIFEST = ROOT / 'manifest.json'


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            digest.update(block)
    return digest.hexdigest()


manifest = json.loads(MANIFEST.read_text())
manifest['status'] = (
    'all planned gates passed; implementation and evidence are on the user fork branch; '
    'no upstream pull request opened'
)
manifest['fork_branch'] = 'perf/iir-stable-block-w4-20261016'
manifest['inputs'] = {
    'sf2': {
        'logical_path': 'MuseScore_General.sf2',
        'location': '$FLUIDSYNTH_E2_ASSET_DIR/MuseScore_General.sf2',
        'sha256': manifest['inputs']['sf2']['sha256'],
    },
    'all_the_small_things': {
        'logical_path': 'Multitrack_MIDIs/All The Small Things.mid',
        'location': '$FLUIDSYNTH_E2_MIDI_ROOT/Multitrack_MIDIs/All The Small Things.mid',
        'sha256': manifest['inputs']['all_the_small_things']['sha256'],
    },
    'maestro_1': {
        'logical_path': 'One_track_MIDIs/Maestro_1.mid',
        'location': '$FLUIDSYNTH_E2_MIDI_ROOT/One_track_MIDIs/Maestro_1.mid',
        'sha256': manifest['inputs']['maestro_1']['sha256'],
    },
    'high_poly_96': {
        'logical_path': 'high_poly_96.mid',
        'location': 'generated by generate_high_poly_96.py in this directory',
        'sha256': manifest['inputs']['high_poly_96']['sha256'],
    },
}
manifest['evidence_sha256']['PR_DESCRIPTION.md'] = sha256(ROOT / 'PR_DESCRIPTION.md')
manifest['evidence_sha256']['refresh_manifest.py'] = sha256(Path(__file__))
manifest['evidence_sha256']['build_probes.sh'] = sha256(ROOT / 'build_probes.sh')
manifest['evidence_sha256']['render_probe_e2.c'] = sha256(ROOT / 'render_probe_e2.c')
manifest['evidence_sha256']['render_probe_extended.c'] = sha256(ROOT / 'render_probe_extended.c')
omitted_paths = {
    item['path'] for item in manifest.get('omitted_binary_evidence', [])
}
omitted_paths.update(item['path'] for item in manifest.get('omitted_files', []))
omitted_paths.update(item['path'] for item in manifest.get('omitted_large_files', []))
for relative_path in sorted(manifest['evidence_sha256']):
    path = ROOT / relative_path
    if not path.is_file():
        if relative_path in omitted_paths:
            continue
        raise SystemExit(f'manifest evidence file is missing: {relative_path}')
    manifest['evidence_sha256'][relative_path] = sha256(path)
manifest['note'] = (
    'evidence_sha256 covers REPORT.md and supporting files as of manifest generation; '
    'external inputs use logical paths and SHA-256 identities, and this manifest does not hash itself.'
)
MANIFEST.write_text(json.dumps(manifest, indent=2) + '\n')
print(f"refreshed {len(manifest['evidence_sha256'])} evidence hashes")
